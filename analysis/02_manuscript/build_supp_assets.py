"""Supplementary numerical values and table rows."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REV = HERE.parent
ROOT = REV.parent
lines, prov = ["% generated by build_supp_assets.py -- do not edit by hand"], []


def put(name, val, src, field):
    lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")
    prov.append({"macro": name, "value": val, "source_file": src, "field": field})


def f(x, d):
    s = f"{x:.{d}f}"
    return s.replace("-", "\\textminus{}") if x < 0 else s


C = json.loads((ROOT / "results" / "confirmation_results.json").read_text())
for m, t in (("J_cbb", "J"), ("I_xdf", "I"), ("J_iid", "Ji"), ("I_xdf_adaptive", "Ia")):
    put(f"sIcpt{t}", f(C["S9_flips"][m]["cal_intercept"], 3), "results/confirmation_results.json", f"S9_flips.{m}.cal_intercept")
M = pd.read_csv(REV / "01_analyses/calibration/results/metrics.csv")
tagD = {"D1": "One", "D2": "Two", "D3": "Three"}
tagK = {"RAW": "Raw", "CONST": "Const", "SCALE": "Scale", "ADD": "Add", "TSCALE": "Tscale", "TADD": "Tadd"}
tagM = {"J_cbb": "J", "I_xdf": "I", "uHAC": "U", "I_cbb": "Ic", "J_iid": "Ji", "-": ""}
for _, r in M[M.kind.isin(tagK)].iterrows():
    v = r.vcr
    d = 2 if v >= 0.1 else (3 if v >= 0.01 else 4)
    put(f"s{tagK[r.kind]}{tagM[r.method]}{tagD[r.D]}Vcr", f(v, d), "01_analyses/calibration/results/metrics.csv", f"{r.D}/{r.kind}/{r.method}.vcr")
(HERE / "supp_values.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

H = pd.read_csv(REV / "01_analyses/model_families/results/hyperparameters.csv")
rows = [f"{int(r.fold) + 1} & {r.M2_C:g} & {r.M3_alpha:g} & {r.M4_C:g} & {r.M4_gamma:.2e} & {int(r.M4_nsv)} \\\\" for _, r in H.iterrows()]
(HERE / "supp_hyper.tex").write_text("\n".join(rows).replace("e-0", "e\\textminus{}0") + "\n", encoding="utf-8")

with open(HERE / "macro_provenance.csv", "a", newline="", encoding="utf-8") as fh:
    w = csv.DictWriter(fh, fieldnames=["macro", "value", "source_file", "field"])
    w.writerows(prov)
print(len(prov), "supplementary macros")
